from dataclasses import dataclass


@dataclass
class ProductWithTax:
    """
    ProductWithTax

    Attributes:
        id_bling: Unique sale ID generated by Bling
        situacao_pedido: Order status within Bling
        sku: Product SKU
        quantidade: Quantity of the item sold
        valor: Product sale value
        icms: Amount paid in ICMS
        pis: Amount paid in PIS
        cofins: Amount paid in COFINS
        difal: Amount paid in DIFAL
        fcp: Amount paid in FCP
        total: Total amount of tax paid on the product sale
    """

    id_bling: int
    order_status: str
    sku: str
    quantity: int
    cost_price: float
    value: float
    icms: float
    pis: float
    cofins: float
    difal: float
    fcp: float
    total: float


@dataclass
class SalesTaxes:
    """
    SalesTaxes

    Attributes:
        id_bling: Unique ID generated by Bling
        icms: ICMS amount paid
        pis: PIS amount paid
        cofins: COFINS amount paid
        difal: DIFAL amount paid
        total: Total tax amount paid on the sale
    """

    id_bling: int
    icms: float
    pis: float
    cofins: float
    difal: float
    fcp: float
    total: float
    cost: float

    @classmethod
    def sum_taxes(cls, produtos_imposto, id_bling) -> 'SalesTaxes':
        """
        Sum of product taxes to generate total taxes for the sale

        :param cls:
        :param produtos_imposto: List of products with individual taxes
        :param id_bling: Unique ID generated by Bling
        :return: Formatted return for sale taxes
        :rtype: SaleTaxes
        """
        return cls(
            id_bling=id_bling,
            icms=sum(p.icms for p in produtos_imposto),
            pis=sum(p.pis for p in produtos_imposto),
            cofins=sum(p.cofins for p in produtos_imposto),
            difal=sum(p.difal for p in produtos_imposto),
            fcp=sum(p.fcp for p in produtos_imposto),
            total=sum(p.total for p in produtos_imposto),
            cost=sum(p.preco_custo for p in produtos_imposto),
        )


@dataclass
class TaxReturn:
    """
    TaxReturn

    Attributes:
        product_tax: It's a list with products itemized with taxes paid.
        sale_tax: These are the total taxes of the sale.

    """

    product_tax: list[ProductWithTax]
    sale_tax: SalesTaxes


